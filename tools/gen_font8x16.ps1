# gen_font8x16.ps1
# Render an 8x16 bitmap font (ASCII 0x20..0x7E, 95 glyphs) into a C++ source file.
# Glyph layout: 16 bytes per glyph, one byte per row, MSB = leftmost pixel.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File gen_font8x16.ps1 -DebugChars
#   powershell -ExecutionPolicy Bypass -File gen_font8x16.ps1 -OutFile <path>\font.cc
#
# Note: glyphs are rasterized from a Windows monospace font (default Consolas).
#       For commercial use, re-render from an open-source font instead.

param(
    [string]$OutFile = "",
    [string]$FontFamily = "Consolas",
    [float]$FontSize = 12,
    [switch]$DebugChars
)

Add-Type -AssemblyName System.Drawing

$bmp = New-Object System.Drawing.Bitmap(8, 16)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
$font = New-Object System.Drawing.Font($FontFamily, $FontSize, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$format = New-Object System.Drawing.StringFormat
$format.Alignment = [System.Drawing.StringAlignment]::Center
$format.LineAlignment = [System.Drawing.StringAlignment]::Center
$rect = New-Object System.Drawing.RectangleF(0, 0, 8, 16)

function Get-GlyphBytes([char]$ch) {
    $g.Clear([System.Drawing.Color]::Black)
    $g.DrawString([string]$ch, $font, [System.Drawing.Brushes]::White, $rect, $format)
    $out = New-Object byte[] 16
    for ($y = 0; $y -lt 16; $y++) {
        $b = 0
        for ($x = 0; $x -lt 8; $x++) {
            $b = $b -shl 1
            if ($bmp.GetPixel($x, $y).R -gt 127) { $b = $b -bor 1 }
        }
        $out[$y] = [byte]$b
    }
    return ,$out
}

if ($DebugChars) {
    foreach ($ch in @('A', 'B', 'a', 'g', 'W', 'i', '5', '@', '#', 'm', '~')) {
        $bytes = Get-GlyphBytes $ch
        Write-Host ("--- '" + $ch + "' ---")
        foreach ($b in $bytes) {
            $line = ""
            for ($x = 7; $x -ge 0; $x--) {
                if (((($b -shr $x) -band 1)) -eq 1) { $line += "#" } else { $line += "." }
            }
            Write-Host $line
        }
    }
    exit 0
}

if ($OutFile -eq "") {
    Write-Host "Please provide -OutFile, or use -DebugChars to preview glyphs."
    exit 1
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('#include "font.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('// NOTE: auto-generated by tools/gen_font8x16.ps1')
[void]$sb.AppendLine('// Layout: 95 glyphs (0x20 ~ 0x7E), 16 bytes each, one byte per row, MSB = leftmost.')
[void]$sb.AppendLine('static const uint8_t kGlyphs[95][16] = {')
for ($code = 0x20; $code -le 0x7E; $code++) {
    $ch = [char]$code
    $hex = "{0:X2}" -f $code
    [void]$sb.AppendLine("    // 0x$hex '$ch'")
    $bytes = Get-GlyphBytes $ch
    $parts = @()
    foreach ($b in $bytes) { $parts += ("0x{0:X2}" -f $b) }
    [void]$sb.AppendLine("    {" + ($parts -join ",") + "},")
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const uint8_t* FontGetGlyph(char c) {')
[void]$sb.AppendLine('    if (c < 0x20 || c > 0x7E) {')
[void]$sb.AppendLine("        c = '?';")
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('    return kGlyphs[static_cast<uint8_t>(c) - 0x20];')
[void]$sb.AppendLine('}')

$dir = Split-Path -Parent $OutFile
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("written: " + $OutFile)
